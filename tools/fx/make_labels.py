#!/usr/bin/env python3
# turns the built-in effects' own descriptions (dump_builtins) into translatable strings and the kotlin lookup that finds them
import json, re, subprocess, sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
d = json.loads(subprocess.check_output([str(Path(__file__).parent / "build" / "dump_builtins")]))

def slug(s):
    return re.sub(r'[^a-z0-9]+', '_', s.replace('&', 'and').lower()).strip('_')

def esc(s):
    return s.replace('&', '&amp;').replace("'", "\\'").replace('"', '\\"').replace('<', '&lt;')

entries = {}
def add(prefix, text):
    if not text or text in entries:
        return
    name, base, n = f'fx_{prefix}_{slug(text)}', f'fx_{prefix}_{slug(text)}', 2
    while name in entries.values():
        name, n = f'{base}_{n}', n + 1
    entries[text] = name

for k in d:
    add('kind', k['name']); add('about', k['description']); add('category', k['category'])
    for p in k['params']:
        add('knob', p['name'])
        for c in p['choices'].split('|'):
            add('choice', c)
    for m in k['meters']:
        add('meter', m['name'])
    for pr in k['presets']:
        add('preset', pr)
add('category', 'Scripts')

xml = ['<?xml version="1.0" encoding="utf-8"?>',
       "<!-- the built-in mixer effects' names, knobs, choices and presets, generated from the native engine's own descriptions (tools/fx/make_labels.py) -->",
       '<resources>'] + [f'    <string name="{n}">{esc(t)}</string>' for t, n in entries.items()] + ['</resources>']
(root / 'app/src/main/res/values/mixer_fx_strings.xml').write_text('\n'.join(xml) + '\n')

kt = ['// MixerLabels.kt', '', 'package com.mochyy.mochymusic.eq.mixer', '', 'import androidx.annotation.StringRes', 'import com.mochyy.mochymusic.R', '',
      "/** the built-in effects describe themselves in english from native code; this finds each text's translatable string (generated by tools/fx/make_labels.py) */",
      'object MixerLabels {', '    private val strings: Map<String, Int> = mapOf(']
for t, n in entries.items():
    kt.append('        "' + t.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$') + f'" to R.string.{n},')
kt += ['    )', '', "    /** the string for a label the engine wrote, null for a module's or a script's own text */", '    @StringRes',
       '    fun of(english: String): Int? = strings[english]', '}', '']
(root / 'app/src/main/kotlin/com/mochyy/mochymusic/eq/mixer/MixerLabels.kt').write_text('\n'.join(kt))
print(len(entries), 'strings')
